"""Parity of `rscm.fair` with FaIR v2.2.5.

The reference runs are generated by ``scripts/fair/generate_fixtures.py``.
Each run is fed its own inputs: emissions for emissions-driven species,
concentrations for concentration-driven ones and forcing for prescribed agents.
The calibrated runs read their configuration with `rscm.fair.read_calibration`
rather than from FaIR's.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from functools import cache
from pathlib import Path
from typing import TYPE_CHECKING, Any

import numpy as np
import numpy.testing as npt
import pandas as pd
import pytest

from rscm.core import (
    GridType,
    InterpolationStrategy,
    ModelBuilder,
    RequirementType,
    TimeAxis,
    Timeseries,
    VariableSchema,
)
from rscm.fair import (
    build_components,
    from_fair,
    initial_values,
    load_config,
    naming,
    prescribed_forcing_scales,
    read_calibration,
    run_ensemble,
    run_fair,
)
from rscm.fair.config import forcing_agents, is_ghg
from rscm.fair.run import _on_timebounds
from rscm.magicc import ClimateUDEBBuilder

if TYPE_CHECKING:
    from numpy.typing import NDArray

    from rscm.core import TimeseriesCollection

DATA = Path(__file__).parent / "data" / "fair"
CALIBRATION = DATA / "calibration"

#: Tolerances against FaIR. Rounding stays orders of magnitude below them.
RTOL = 1e-9
ATOL = 1e-12

#: fair-calibrate v1.6.1 posterior members with a reference run.
CALIBRATION_MEMBERS = tuple(
    int(m)
    for m in pd.read_csv(
        CALIBRATION / "calibrated_constrained_parameters.csv", index_col=0
    ).index
)

CASES = (
    "ebm_3layer",
    "ebm_2layer",
    "ebm_3layer_5yr",
    "major_ghg_ssp245",
    "ssp245",
    "ssp119",
    "ssp245_leach",
    "ssp245_5yr",
    "ssp245_concentration",
    *(f"calibrated_{member}" for member in CALIBRATION_MEMBERS),
)
CHEMISTRY_CASES = (
    "ssp245",
    "ssp119",
    "ssp245_5yr",
    "ssp245_concentration",
    *(f"calibrated_{member}" for member in CALIBRATION_MEMBERS),
)


@dataclass(frozen=True)
class Run:
    """A FaIR reference run and the RSCM model of it."""

    config: dict[str, Any]
    timebounds: pd.DataFrame
    timepoints: pd.DataFrame
    outputs: TimeseriesCollection

    def rscm(self, variable: str) -> NDArray[np.float64]:
        """Values of an RSCM variable on the timebounds."""
        series = self.outputs.get_timeseries_by_name(variable)
        assert series is not None, variable
        return np.asarray(series.values())

    def fair(self, column: str) -> NDArray[np.float64]:
        """Values of a FaIR timebound column."""
        return self.timebounds[column].to_numpy()


def _read(path: Path) -> pd.DataFrame:
    return pd.read_csv(path, index_col=0, float_precision="round_trip")


def _inputs(
    config: dict[str, Any], timebounds: pd.DataFrame, timepoints: pd.DataFrame
) -> dict[str, tuple[NDArray[np.float64], str]]:
    inputs = {}
    for s in config["species"]:
        exogenous = naming.exogenous_variable(s)
        if exogenous is not None:
            variable, unit = exogenous
            mode = s["input_mode"]
            frame = timepoints if mode == "emissions" else timebounds
            inputs[variable] = (frame[f"{mode}|{s['name']}"].to_numpy(), unit)
    return inputs


@cache
def calibration() -> dict[Any, dict[str, Any]]:
    """Read the configurations of the calibrated members."""
    return read_calibration(
        CALIBRATION / "species_configs_properties.csv",
        CALIBRATION / "calibrated_constrained_parameters.csv",
    )


@cache
def load(case: str) -> Run:
    """Run RSCM on the inputs of a reference run."""
    config = (
        calibration()[int(case.removeprefix("calibrated_"))]
        if case.startswith("calibrated_")
        else load_config(DATA / f"{case}.json")
    )
    timebounds = _read(DATA / f"{case}_timebounds.csv.gz")
    timepoints = _read(DATA / f"{case}_timepoints.csv.gz")
    model = run_fair(
        config,
        _inputs(config, timebounds, timepoints),
        timebounds.index.to_numpy(),
    )
    return Run(config, timebounds, timepoints, model.timeseries())


def assert_close(actual: Any, expected: Any, err_msg: str = "") -> None:
    """Assert RSCM agrees with FaIR within `RTOL` and `ATOL`."""
    npt.assert_allclose(actual, expected, rtol=RTOL, atol=ATOL, err_msg=err_msg)


@pytest.mark.parametrize("case", CASES)
def test_climate(case: str) -> None:
    run = load(case)
    for layer in range(len(run.config["climate"]["ocean_heat_capacity"])):
        assert_close(
            run.rscm(naming.layer_temperature(layer)),
            run.fair(f"temperature|{layer}"),
            f"layer {layer}",
        )
    assert_close(run.rscm(naming.ENERGY_IMBALANCE), run.fair("toa_imbalance"))
    assert_close(
        run.rscm(naming.OCEAN_HEAT_CONTENT_CHANGE),
        run.fair("ocean_heat_content_change"),
    )
    assert_close(run.rscm(naming.STOCHASTIC_FORCING), run.fair("stochastic_forcing"))
    assert_close(run.rscm(naming.TOTAL_FORCING), run.fair("forcing_sum"))


@pytest.mark.parametrize("case", CASES)
def test_forcing(case: str) -> None:
    run = load(case)
    for s in forcing_agents(run.config):
        if s["input_mode"] != "forcing":
            assert_close(
                run.rscm(naming.forcing(s)), run.fair(f"forcing|{s['name']}"), s["name"]
            )


@pytest.mark.parametrize("case", [c for c in CASES if not c.startswith("ebm")])
def test_gas_cycle(case: str) -> None:
    run = load(case)
    for s in filter(is_ghg, run.config["species"]):
        name = s["name"]
        if s["input_mode"] == "concentration":
            # RSCM writes the emissions of a step at its end, FaIR at its start.
            assert_close(
                run.rscm(naming.emissions(name))[1:],
                run.timepoints[f"emissions|{name}"].to_numpy(),
                name,
            )
        else:
            assert_close(
                run.rscm(naming.concentration(name)),
                run.fair(f"concentration|{name}"),
                name,
            )
        assert_close(
            run.rscm(naming.airborne_emissions(name)),
            run.fair(f"airborne_emissions|{name}"),
            name,
        )
        assert_close(
            run.rscm(naming.cumulative_emissions(name)),
            run.fair(f"cumulative_emissions|{name}"),
            name,
        )


@pytest.mark.parametrize("case", CHEMISTRY_CASES)
def test_chemistry(case: str) -> None:
    run = load(case)
    assert_close(
        run.rscm(naming.EESC),
        run.fair("concentration|Equivalent effective stratospheric chlorine"),
    )
    # FaIR stores the scaling used in a step at its start.
    assert_close(
        run.rscm(naming.CH4_LIFETIME_SCALING)[1:], run.fair("alpha_lifetime|CH4")[:-1]
    )


def _same(actual: Any, expected: Any) -> bool:
    if isinstance(actual, list):
        return len(actual) == len(expected) and all(map(_same, actual, expected))
    if isinstance(actual, float) and (expected is None or math.isnan(expected)):
        return math.isnan(actual)
    return bool(actual == expected)


@pytest.mark.parametrize("member", CALIBRATION_MEMBERS)
def test_calibration_matches_fair(member: int) -> None:
    config = calibration()[member]
    expected = load_config(DATA / f"calibrated_{member}.json")
    assert config["options"] == expected["options"]
    assert _same(
        config["climate"], {k: expected["climate"][k] for k in config["climate"]}
    )
    for key, value in config["species_configs"].items():
        assert _same(value, expected["species_configs"][key]), key
    assert [s["name"] for s in config["species"]] == [
        s["name"] for s in expected["species"]
    ]
    for entry, fair_entry in zip(config["species"], expected["species"]):
        for key, value in entry.items():
            assert _same(value, fair_entry[key]), (entry["name"], key)


def test_ensemble() -> None:
    xr = pytest.importorskip("xarray")
    configs = calibration()
    runs = {member: load(f"calibrated_{member}") for member in CALIBRATION_MEMBERS}
    first = runs[CALIBRATION_MEMBERS[0]]
    inputs = _inputs(first.config, first.timebounds, first.timepoints)
    # Undo the first member's forcing scale so each member applies its own.
    for variable, scale in prescribed_forcing_scales(first.config).items():
        values, unit = inputs[variable]
        inputs[variable] = (values / scale, unit)

    result = run_ensemble(
        configs,
        {"historical": inputs},
        first.timebounds.index.to_numpy(),
        scale_prescribed_forcing=True,
    )

    assert isinstance(result, xr.Dataset)
    for member, run in runs.items():
        member_result = result.sel(scenario="historical", config=member)
        for layer in range(3):
            assert_close(
                member_result.temperature.sel(layer=layer),
                run.fair(f"temperature|{layer}"),
            )
        assert_close(member_result.forcing_sum, run.fair("forcing_sum"))
        for attribute in ("concentration", "forcing", "airborne_emissions"):
            compared = 0
            for specie in result.specie.values:
                actual = member_result[attribute].sel(specie=specie)
                if not np.isnan(actual.to_numpy()).all():
                    assert_close(actual, run.fair(f"{attribute}|{specie}"), specie)
                    compared += 1
            ghgs = sum(map(is_ghg, run.config["species"]))
            assert (
                compared
                == {
                    "concentration": ghgs + 1,
                    "forcing": len(forcing_agents(run.config)),
                    "airborne_emissions": ghgs,
                }[attribute]
            )
        for column in run.timepoints.columns:
            specie = column.removeprefix("emissions|")
            assert_close(
                member_result.emissions.sel(specie=specie),
                run.timepoints[column],
                column,
            )


def test_from_fair() -> None:
    fair = pytest.importorskip("fair")
    from fair.interface import fill, initialise  # noqa: PLC0415
    from fair.io import read_properties  # noqa: PLC0415

    member = CALIBRATION_MEMBERS[0]
    run = load(f"calibrated_{member}")
    species_file = CALIBRATION / "species_configs_properties.csv"
    species, properties = read_properties(species_file)
    f = fair.FAIR(ch4_method="thornhill2021")
    f.define_time(1750, 2024, 1)
    f.define_scenarios(["historical"])
    f.define_configs([member])
    f.define_species(species, properties)
    f.allocate()
    f.fill_species_configs(species_file)
    f.override_defaults(CALIBRATION / "calibrated_constrained_parameters.csv")
    fill(f.climate_configs["stochastic_run"], False)
    for column in run.timepoints.columns:
        fill(
            f.emissions,
            run.timepoints[column].to_numpy()[:, None, None],
            specie=column.removeprefix("emissions|"),
        )
    for s in species:
        if properties[s]["input_mode"] == "forcing":
            fill(f.forcing, run.fair(f"forcing|{s}")[:, None, None], specie=s)
    initialise(f.concentration, f.species_configs["baseline_concentration"])

    config, inputs, timebounds = from_fair(f)

    assert config["options"] == run.config["options"]
    outputs = run_fair(config, inputs, timebounds).timeseries()
    for variable, column in (
        (naming.SURFACE_TEMPERATURE, "temperature|0"),
        (naming.TOTAL_FORCING, "forcing_sum"),
        (naming.concentration("CO2"), "concentration|CO2"),
    ):
        series = outputs.get_timeseries_by_name(variable)
        assert series is not None, variable
        assert_close(series.values(), run.fair(column), variable)


def test_climate_udeb_smoke() -> None:
    """FaIR's gas cycle and forcing drive MAGICC's ClimateUDEB in place of the EBM."""
    member = CALIBRATION_MEMBERS[0]
    run = load(f"calibrated_{member}")
    nh, sh = 0.42, 0.21
    climate = ClimateUDEBBuilder.from_parameters(
        {"ecs": 3.0, "nh_land_fraction": nh, "sh_land_fraction": sh}
    )
    components = [*build_components(run.config, energy_balance=False), climate.build()]

    schema = VariableSchema()
    definitions = [d for c in components for d in c.definitions()]
    # Writers first, so the schema keeps ClimateUDEB's four-box temperature.
    for d in sorted(
        definitions, key=lambda d: d.requirement_type == RequirementType.Input
    ):
        if d.requirement_type != RequirementType.EmptyLink and not schema.contains(
            d.name
        ):
            schema.add_variable(d.name, d.unit, d.grid_type)

    axis = TimeAxis.from_values(run.timebounds.index.to_numpy(dtype=np.float64))
    builder = (
        ModelBuilder()
        .with_time_axis(axis)
        .with_schema(schema)
        .with_grid_weights(
            GridType.FourBox, [(1 - nh) / 2, nh / 2, (1 - sh) / 2, sh / 2]
        )
    )
    for component in components:
        builder.with_rust_component(component)
    inputs = _inputs(run.config, run.timebounds, run.timepoints)
    n_bounds = len(axis.values())
    for name, (values, unit) in inputs.items():
        builder.with_exogenous_variable(
            name,
            Timeseries(
                _on_timebounds(name, values, n_bounds),
                axis,
                unit,
                InterpolationStrategy.Previous,
            ),
        )
    builder.with_initial_values(
        {
            **initial_values(run.config, energy_balance=False),
            **climate.initial_values(0.0),
        }
    )
    model = builder.build()
    model.run()

    outputs = model.timeseries()
    temperature = outputs.get_fourbox_timeseries_by_name(naming.SURFACE_TEMPERATURE)
    assert temperature is not None
    co2 = outputs.get_timeseries_by_name(naming.concentration("CO2"))
    assert co2 is not None
    warming = temperature.values()[-1] @ [(1 - nh) / 2, nh / 2, (1 - sh) / 2, sh / 2]
    assert 0.5 < warming < 2.0
    # The climate differs from FaIR's, so CO2 only roughly follows its feedback.
    npt.assert_allclose(co2.values()[-1], run.fair("concentration|CO2")[-1], rtol=0.02)
