def _sectors(df, variable):
    """Sum the MAGICC fossil and AFOLU sectors of an emissions variable."""
    years, fossil = get_variable_values(df, f"{variable}|MAGICC Fossil and Industrial")
    _, afolu = get_variable_values(df, f"{variable}|MAGICC AFOLU")
    return years, fossil + afolu


def test_03_emissions_driven():
    """
    Test 3: Emissions-driven run with coupled carbon cycle and chemistry.

    CO2, CH4 and N2O are calculated from SSP245 emissions from 1750, with
    temperature feeding back on the carbon cycle and chemistry. Forcing outside
    the three gases is prescribed from the reference. Natural emissions use the
    budget-closing values MAGICC7 reports.

    The reference disables permafrost, volcanic and solar forcing and internal
    variability (see the generator). Remaining differences come mainly from the
    first-year and substep conventions of the climate model.
    """
    df, _config = load_data("03_emissions_driven")
    years, _ = get_variable_values(df, "Surface Temperature")

    def series(variable):
        return get_variable_values(df, variable)[1]

    def interval(values):
        return values[:-1]

    emissions = Emissions(
        co2_fossil=interval(series("Emissions|CO2|MAGICC Fossil and Industrial")),
        co2_land_use=interval(series("Emissions|CO2|MAGICC AFOLU")),
        ch4=interval(_sectors(df, "Emissions|CH4")[1]),
        ch4_fossil=interval(series("Emissions|CH4|MAGICC Fossil and Industrial")),
        n2o=interval(_sectors(df, "Emissions|N2O")[1]),
        nox=interval(_sectors(df, "Emissions|NOx")[1]),
        co=interval(_sectors(df, "Emissions|CO")[1]),
        nmvoc=interval(_sectors(df, "Emissions|NMVOC")[1]),
    )
    concentrations = {
        gas: series(f"Atmospheric Concentrations|{gas}")
        for gas in ("CO2", "CH4", "N2O")
    }
    initial = {gas: float(values[0]) for gas, values in concentrations.items()}
    erf = "Effective Radiative Forcing"
    other = series(erf) - sum(series(f"{erf}|{gas}") for gas in initial)

    result = run_magicc_emissions(
        years,
        emissions,
        initial_concentrations=initial,
        other_forcing=other,
        parameters={
            "GhgForcing": {f"{gas.lower()}_pi": c for gas, c in initial.items()},
            "CH4Chemistry": {"natural_emissions": float(series("CH4N_EMIS")[0])},
            "N2OChemistry": {"natural_emissions": float(series("N2ON_EMIS")[0])},
            "ClimateUDEB": {"ecs": 3.0},
        },
    )
    values = result.values

    for gas, rtol in (("CO2", 2e-3), ("CH4", 3e-3), ("N2O", 2e-4)):
        assert_allclose_recorded(
            values[f"Atmospheric Concentration|{gas}"],
            concentrations[gas],
            rtol=rtol,
            atol=DEFAULT_ATOL,
            suite=SUITE,
            name="03_emissions",
            variable=f"Conc|{gas}",
        )
    assert_allclose_recorded(
        values["Surface Temperature"],
        series("Surface Temperature"),
        rtol=0.0,
        atol=0.03,
        suite=SUITE,
        name="03_emissions",
        variable="Temperature",
    )

    # MAGICC7 labels the ocean flux and CH4 oxidation of each year at its end,
    # like RSCM, but the land flux and lifetimes at its start.
    npt.assert_allclose(
        values["Carbon Flux|Ocean"][1:],
        series("Net Atmosphere to Ocean Flux|CO2")[1:],
        atol=0.03,
    )
    npt.assert_allclose(
        values["Emissions|CO2|CH4 Oxidation"][1:],
        series("CH4_2CO2_OXIDISATION_EMIS")[:-1],
        rtol=5e-3,
        atol=1e-4,
    )
    npt.assert_allclose(
        values["Carbon Flux|Terrestrial"][1:],
        series("Net Atmosphere to Land Flux|CO2")[:-1],
        atol=0.05,
    )
    for gas, variable in (("CH4", "CH4_TAUTOT"), ("N2O", "N2O_TAUTOT")):
        npt.assert_allclose(
            values[f"Lifetime|{gas}"][1:], series(variable)[:-1], rtol=2e-3
        )


@pytest.mark.parametrize("ecs", [1.5, 2.0, 3.0, 4.0, 4.5])
def test_04_ecs_sweep(ecs: float):
    """
    Test 4: Climate sensitivity parameter sweep (ERF -> temperature only).

    Decoupled test that validates the ClimateUDEB temperature response
    independently of forcing calculation. Feeds reference ERF|CO2 directly
    as exogenous forcing into the climate component.

    Parameters
    ----------
    ecs
        Equilibrium Climate Sensitivity value in Kelvin

    Variables compared:
    - Surface Temperature (global mean from FourBox output)
    """
    df, config = load_data(f"04_ecs_sweep_{ecs}")

    # Verify config matches expected ECS
    assert config.get("core_climatesensitivity") == ecs

    # Extract reference ERF as exogenous input (decoupled from concentration calc)
    years, erf_co2 = get_variable_values(df, "Effective Radiative Forcing|CO2")
    _, expected_temp = get_variable_values(df, "Surface Temperature")

    # Build ERF -> temperature model (ClimateUDEB only)
    model = build_erf_to_temperature_model(years, erf_co2, config)
    model.run()

    results = model.timeseries()

    # Extract FourBox surface temperature and compute global mean.
    # Surface Temperature is a state variable with a valid initial value (0.0)
    # at index 0, so no [1:] shift is needed (unlike computed outputs like ERF
    # which are NaN at index 0).
    temp_4box = results.get_fourbox_timeseries_by_name("Surface Temperature")
    assert temp_4box is not None, "Surface Temperature not found in results"
    actual_temp = fourbox_global_mean(temp_4box.values())

    assert_allclose_phased(
        actual_temp,
        expected_temp,
        shock_rtol=5e-2,
        converge_rtol=3e-2,
        final_rtol=3e-2,
        atol=DEFAULT_ATOL,
        suite="ghg_forcing",
        name=f"04_ecs_sweep_{ecs}",
        variable="Surface Temperature",
    )


def test_05_co2_only_forcing():
    """
    Test 5: CO2-only forcing mode (ERF -> temperature).

    Decoupled test that validates ClimateUDEB using CO2-only forcing.
    In this mode, total ERF equals CO2 ERF, providing the simplest
    possible forcing pathway for clean temperature validation.

    Config:
    - rf_total_runmodus: CO2 (only CO2 forcing contributes)

    Variables compared:
    - Effective Radiative Forcing (sanity: total == CO2)
    - Surface Temperature (global mean from FourBox output)
    """
    df, config = load_data("05_co2_only_forcing")

    # Verify config
    assert config.get("rf_total_runmodus") == "CO2"

    # Extract expected values
    years, expected_total_erf = get_variable_values(df, "Effective Radiative Forcing")
    _, expected_erf_co2 = get_variable_values(df, "Effective Radiative Forcing|CO2")
    _, expected_temp = get_variable_values(df, "Surface Temperature")

    # In CO2-only mode, total ERF should equal CO2 ERF
    npt.assert_allclose(expected_total_erf, expected_erf_co2, rtol=1e-6)

    # Build ERF -> temperature model (ClimateUDEB only)
    model = build_erf_to_temperature_model(years, expected_total_erf, config)
    model.run()

    results = model.timeseries()

    # Extract FourBox surface temperature and compute global mean.
    # Surface Temperature is a state variable with a valid initial value (0.0)
    # at index 0, so no [1:] shift is needed.
    temp_4box = results.get_fourbox_timeseries_by_name("Surface Temperature")
    assert temp_4box is not None, "Surface Temperature not found in results"
    actual_temp = fourbox_global_mean(temp_4box.values())

    assert_allclose_phased(
        actual_temp,
        expected_temp,
        shock_rtol=5e-2,
        converge_rtol=3e-2,
        final_rtol=3e-2,
        atol=DEFAULT_ATOL,
        suite="ghg_forcing",
        name="05_co2_only",
        variable="Surface Temperature",
    )
