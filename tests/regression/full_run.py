@cache
def prescribed_forcing() -> dict[str, NDArray[np.float64]]:
    """Four-box ERF of every agent MAGICC7 calculates before the run."""
    run = load()
    return full.prescribed_forcing(
        run.years, emissions(run), run.parameters, full.load_inputs(run.parameters)
    )


def climate_parameters(run: FullRun) -> dict[str, Any]:
    """ClimateUdeb parameters of the reference run."""
    return full.climate_parameters(
        run.parameters, full.load_inputs(run.parameters), run.years[0]
    )


def _sum(terms: list[NDArray[np.float64]]) -> NDArray[np.float64]:
    total = terms[0]
    for term in terms[1:]:
        total = total + term
    return total


def prescribed_global_forcing(run: FullRun) -> dict[str, NDArray[np.float64]]:
    """Global ERF of each prescribed agent as MAGICC7 reports it.

    MAGICC7 scales the global of a harmonised agent's unscaled boxes,
    rather than taking the global of its scaled boxes.
    """
    p, y = run.parameters, run.years
    files = full.load_inputs(p)
    em = emissions(run)
    boxes = full.prescribed_forcing(y, em, p, files)
    out = {name: pr.area_mean(boxes[name]) for name in ("NO3|Fossil", "NO3|AFOLU")}
    out["Cloud Albedo"] = pr.area_mean(boxes["Cloud Albedo"])
    out["Solar"] = boxes["Solar"][:, 0]
    for species in ("SOx", "BC", "OC"):
        code = species.lower()
        industrial = files[f"file_{code}i_rf"]
        fossil = em[f"{species}|Fossil"]
        raw = pr._extend(industrial, y, fossil - fossil[0])
        year, target = p[f"rf_{code}i_dir_yr"], p[f"rf_{code}i_dir_wm2"]
        i = pr._switch_index(y, year)
        # A target of the unscaled change gives a factor of exactly 1.
        unscaled = pr.direct_aerosol(
            y,
            industrial,
            files[f"file_{code}b_rf"],
            fossil,
            em[f"{species}|AFOLU"],
            target=float(pr.area_mean(raw[i]) - pr.area_mean(raw[0])),
            target_year=year,
        )
        factor = pr._harmonise(raw, y, year, target)
        for sector, values in zip(("Fossil", "AFOLU"), unscaled):
            out[f"{species}|{sector}"] = pr.area_mean(values) * factor
    raw = pr._extend(files["file_bcsnow_rf"], y, em["BC|Fossil"] + em["BC|AFOLU"])
    factor = pr._harmonise(raw, y, p["rf_bcsnow_albedo_yr"], p["rf_bcsnow_albedo_wm2"])
    snow = pr.area_mean(raw)
    out["BC on Snow"] = snow * factor - snow[0] * factor
    land_use = files["file_landuse_rf"]
    raw = pr._extend(land_use, y, np.cumsum(em["CO2|AFOLU"]), before=0.0)
    factor = pr._harmonise(
        raw, y, p["rf_landuse_albedo_yr"], p["rf_landuse_albedo_wm2"]
    )
    hold = pr._hold_after(pr.area_mean(raw), y, p["rf_landuse_constantafteryr"])
    out["Land Use"] = hold * factor
    dust = pr.area_mean(raw)
    i = pr._switch_index(y, p["rf_mineraldust_dir_yr"])
    scaled = dust * (p["rf_mineraldust_dir_wm2"] / (dust[i] - dust[0]))
    out["Mineral Dust"] = pr._hold_after(scaled, y, p["rf_mineraldust_constantafteryr"])
    return out


class Reported:
    """ERF of a coupled run as MAGICC7 reports it.

    MAGICC7 applies RF * factor, where the factor is 1, 1 / inteff or eff / inteff
    as ``rf_efficacy_apply`` is 0, 1 or 2, with each year's internal efficacy.
    It reports (RF * factor) * inteff.
    """

    def __init__(self, run: FullRun, model: Model) -> None:
        self.run = run
        self.model = model
        p = run.parameters
        climate = climate_parameters(run)
        prescribed = full.prescribed_forcing(
            run.years, emissions(run), p, full.load_inputs(p)
        )
        agents = full.forcing_agents(p, run.years, prescribed, emissions(run))
        aggregation = ForcingAggregationBuilder.from_parameters(
            {
                "agents": agents,
                "efficacy_method": full.EFFICACY_METHODS[p["rf_efficacy_apply"]],
                "climate": full.efficacy_climate(climate),
            }
        )
        initial = aggregation.internal_efficacies(
            climate["ecs"], full.EFFICACY_ERF_2XCO2
        )
        ecs = output(model, "Equilibrium Climate Sensitivity")
        erf_2xco2 = output(model, f"{ERF}|2xCO2")
        # Each year applies the internal efficacies of the previous year's climate.
        internal = [initial] + [
            aggregation.internal_efficacies(e, q) if np.isfinite(e) else initial
            for e, q in zip(ecs[:-1], erf_2xco2[:-1])
        ]
        self._names = [a["variable"].removeprefix(f"{ERF}|") for a in agents]
        self._efficacies = [a["efficacy"] for a in agents]
        self._internal = np.array(internal)
        self._apply = p["rf_efficacy_apply"]

    def erf(self, agent: str, forcing: NDArray[np.float64]) -> NDArray[np.float64]:
        """Reported ERF of `agent` from the forcing before efficacies.

        An AFOLU aerosol takes the internal efficacy of its fossil counterpart.
        """
        i = self._names.index(agent.replace("|AFOLU", "|Fossil"))
        inteff = self._internal[:, i]
        if forcing.ndim == 2:
            inteff = inteff[:, None]
        factor = {0: 1.0, 1: 1.0 / inteff}.get(
            self._apply, self._efficacies[i] / inteff
        )
        return (forcing * factor) * inteff

    @cached_property
    def _halocarbon_model(self) -> Model:
        """Global species forcing from the run's concentrations, before box split."""
        species = full.halocarbon_species()
        concentrations = {
            s: output(self.model, f"Atmospheric Concentration|{s}") for s in species
        }
        n = len(self.run.years)
        component = HalocarbonChemistryBuilder.from_parameters(
            {"fgas_switch_year": np.inf, "montreal_gases_switch_year": np.inf}
        ).build()
        return run_components(
            self.run.time_axis,
            [component],
            prescribed={
                **{
                    f"Atmospheric Concentration|{s}|Prescribed": (c, "ppt")
                    for s, c in concentrations.items()
                },
                **{f"Emissions|{s}": (np.zeros(n), "kt/yr") for s in species},
                "Lifetime|CH4|OH": (np.ones(n), "yr"),
                "Surface Temperature": (np.zeros(n), "K"),
            },
            initial_values={
                f"Atmospheric Concentration|{s}": c[0]
                for s, c in concentrations.items()
            },
        )

    def halocarbons(self, group: str) -> NDArray[np.float64]:
        """Reported ERF of a halocarbon group, the sum of its species' reported ERF."""
        return _sum(
            [
                self.erf(group, output(self._halocarbon_model, name))
                for name in full.halocarbon_forcing(group)
            ]
        )

    def total(self) -> NDArray[np.float64]:
        """Reported total ERF, with MAGICC7's own volcanic ERF."""
        leaves = {
            name: self.erf(name, output(self.model, f"{ERF}|{name}"))
            for name in (
                "CO2",
                "CH4",
                "N2O",
                "Stratospheric Ozone",
                "Ozone due to N2O",
                "Ozone due to Temperature",
                "CH4 Oxidation Stratospheric H2O",
            )
        }
        for group in ("F-Gases", "Montreal Protocol Halogen Gases"):
            leaves[group] = self.halocarbons(group)
        trop = "Tropospheric Ozone"
        boxes = self.model.timeseries().get_four_box_timeseries_by_name(f"{ERF}|{trop}")
        leaves[trop] = self.erf(trop, pr.area_mean(boxes.values()))
        prescribed = prescribed_global_forcing(self.run)
        leaves.update({n: self.erf(n, v) for n, v in prescribed.items()})
        biomass = _sum([prescribed[name] for name in full.BIOMASS_AGENTS])
        leaves[full.BIOMASS] = self.erf(full.BIOMASS, biomass)

        def tree(term: Any) -> NDArray[np.float64]:
            return (
                _sum([tree(t) for t in term])
                if isinstance(term, list)
                else leaves[term]
            )

        anthropogenic = tree([t for t in full.SUMMATION if t != "Solar"])
        return (anthropogenic + leaves["Solar"]) + self.run.series(f"{ERF}|Volcanic")


@cache
def default_model() -> Model:
    """`full.run_magicc7` with its packaged defaults on the reference emissions."""
    run = load_default()
    return full.run_magicc7(run.time_axis, emissions(run))


@cache
def reported() -> Reported:
    """Reporting of the reference run's coupled RSCM run."""
    run = load()
    return Reported(run, run_coupled(run))


def run_coupled(run: FullRun) -> Model:
    """Run the full RSCM MAGICC chain from the reference run's emissions and inputs."""
    # MAGICC7 reports an F-gas's second-year concentration in its first year.
    n_fgas = run.parameters["fgas_n"]
    species = ("CO2", "CH4", "N2O", *full.halocarbon_species()[n_fgas:])
    return full.run_magicc7(
        run.time_axis,
        emissions(run),
        parameters=run.parameters,
        initial_concentrations={
            s: run.series(f"Atmospheric Concentrations|{s}")[0] for s in species
        },
    )
