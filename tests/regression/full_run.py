"""Access to the full emissions-driven MAGICC reference run.

The fixture is MAGICC7 v7.5.3 SSP245 with the default configuration,
emissions-driven from 1750, generated by
``scripts/regression/generate_full_run.py``.
A second run enables permafrost, a third nitrogen limitation
and a fourth writes sea level rise.
Each keeps only the variables it changes.
"""

