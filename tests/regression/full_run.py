"""Access to the full emissions-driven MAGICC reference run.

The fixture is MAGICC7 v7.5.3 SSP245 with the default configuration,
emissions-driven from 1750, generated by
``scripts/regression/generate_full_run.py``.
A second run enables permafrost, a third nitrogen limitation
and a fourth writes sea level rise.
Each keeps only the variables it changes.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import cache, cached_property
from pathlib import Path
from typing import TYPE_CHECKING, Any

import numpy as np
import numpy.testing as npt
import pandas as pd
import pytest

from rscm.core import TimeAxis
from rscm.magicc import ForcingAggregationBuilder, HalocarbonChemistryBuilder, full
from rscm.magicc import prescribed as pr
from rscm.magicc.full import DIRECT, run_components
from rscm.names import (
    EFFICACY_ADJUSTED_ERF,
    ERF,
    ERF_2XCO2,
    LIFETIME_CH4_OH,
    SECTORS,
    SURFACE_AIR_TEMPERATURE_CHANGE,
    Convention,
    convert_variable_name,
    emissions_conversion_factor,
    prescribed,
)

if TYPE_CHECKING:
    from numpy.typing import NDArray

    from rscm.core import Model

__all__ = ["EFFICACY_ADJUSTED_ERF", "ERF", "run_components"]

DATA = Path(__file__).parent / "data" / "full_run" / "01_ssp245_emissions"
PERMAFROST = DATA.with_name("02_ssp245_emissions_permafrost")
NITROGEN = DATA.with_name("03_ssp245_emissions_nitrogen")
DEFAULT = DATA.with_name("05_ssp245_default")
SEALEVEL = DATA.with_name("04_ssp245_emissions_sealevel")

# MAGICC region names in RSCM four-box order.
BOXES = (
    "World|Northern Hemisphere|Ocean",
    "World|Northern Hemisphere|Land",
    "World|Southern Hemisphere|Ocean",
    "World|Southern Hemisphere|Land",
)

# Relative and absolute tolerances against MAGICC7.
# Rounding stays orders of magnitude below them and any modelling change far above.
RTOL = 1e-9
ATOL = 1e-12

# Global area fractions of the boxes with MAGICC7's default land fractions.
AREA = pr.area_fractions()


def assert_close(actual: Any, expected: Any, err_msg: str = "") -> None:
    """Assert RSCM agrees with MAGICC7 within `RTOL` and `ATOL`."""
    npt.assert_allclose(actual, expected, rtol=RTOL, atol=ATOL, err_msg=err_msg)


@dataclass(frozen=True)
class FullRun:
    """The reference run, indexed by RSCM variable name and region.

    Values keep MAGICC7's units.
    """

    data: pd.DataFrame
    parameters: dict[str, Any]

    @property
    def years(self) -> NDArray[np.float64]:
        """Annual labels of the run."""
        return self.data.columns.to_numpy(dtype=np.float64)

    @property
    def time_axis(self) -> TimeAxis:
        """Time axis with a step starting at each annual label."""
        return TimeAxis.from_values(self.years)

    def series(self, variable: str, region: str = "World") -> NDArray[np.float64]:
        """Global (or one region's) values of a variable."""
        return self.data.loc[(variable, region)].to_numpy(dtype=np.float64)

    def boxes(self, variable: str) -> NDArray[np.float64]:
        """Four-box values of a variable with shape (years, 4)."""
        return np.stack([self.series(variable, box) for box in BOXES], axis=1)


def _json(stem: Path, suffix: str) -> Any:
    with open(stem.with_name(f"{stem.name}_{suffix}.json")) as f:
        return json.load(f)


def _read_data(stem: Path) -> pd.DataFrame:
    path = stem.with_name(stem.name + ".csv.gz")
    if not path.exists():
        pytest.skip(f"Reference data not found: {path}")
    raw = pd.read_csv(path, float_precision="round_trip")
    raw["variable"] = raw["variable"].map(convert_variable_name)
    wide = raw.set_index(["variable", "region"])
    years = [c for c in wide.columns if c[:4].isdigit()]
    wide = wide[years]
    wide.columns = [int(c[:4]) for c in years]
    return wide


def _read(stem: Path) -> FullRun:
    raw = _json(stem, "parameters")
    defaults = full.default_parameters()
    inputs = {key: defaults[key] for key in full.REWRITTEN_PARAMETERS}
    return FullRun(_read_data(stem), {**raw["allcfgs"], **raw["outputcfgs"], **inputs})


@cache
def load() -> FullRun:
    """Load the reference run, skipping the test if it is missing."""
    return _read(DATA)


def _with_inputs(run: FullRun) -> FullRun:
    base = load()
    inputs = base.data[~base.data.index.isin(run.data.index)]
    return FullRun(pd.concat([run.data, inputs]), run.parameters)


@cache
def load_permafrost() -> FullRun:
    """Load the permafrost run, with the reference run's unchanged inputs."""
    return _with_inputs(_read(PERMAFROST))


@cache
def load_default() -> FullRun:
    """Load MAGICC7's default run, which prescribes concentrations until 2015."""
    return _with_inputs(_read(DEFAULT))


@cache
def load_nitrogen() -> FullRun:
    """Load the nitrogen limitation run, with the reference run's unchanged inputs."""
    return _with_inputs(_read(NITROGEN))


@cache
def load_sealevel() -> FullRun:
    """Load the sea level run, with the reference run's unchanged inputs."""
    return _with_inputs(_read(SEALEVEL))


